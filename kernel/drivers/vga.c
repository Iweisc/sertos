void vga_clear_screen(uint8_t color) {
    for (int i = 0; i < VGA_WIDTH * VGA_HEIGHT; i++) {
        vga_memory[i] = color;
    }
}

void vga_put_pixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < VGA_WIDTH && y >= 0 && y < VGA_HEIGHT) {
        vga_memory[y * VGA_WIDTH + x] = color;
    }
}

uint8_t vga_get_pixel(int x, int y) {
    if (x >= 0 && x < VGA_WIDTH && y >= 0 && y < VGA_HEIGHT) {
        return vga_memory[y * VGA_WIDTH + x];
    }
    return 0;
}

void vga_draw_rect(int x, int y, int width, int height, uint8_t color) {
    for (int i = x; i < x + width; i++) {
        vga_put_pixel(i, y, color);
        vga_put_pixel(i, y + height - 1, color);
    }
    for (int i = y; i < y + height; i++) {
        vga_put_pixel(x, i, color);
        vga_put_pixel(x + width - 1, i, color);
    }
}

void vga_draw_rect_filled(int x, int y, int width, int height, uint8_t color) {
    for (int j = y; j < y + height; j++) {
        for (int i = x; i < x + width; i++) {
            vga_put_pixel(i, j, color);
        }
    }
}

void vga_draw_line(int x1, int y1, int x2, int y2, uint8_t color) {
    int dx = x2 - x1;
    int dy = y2 - y1;
    int sx = (dx > 0) ? 1 : -1;
    int sy = (dy > 0) ? 1 : -1;
    
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;
    
    int err = dx - dy;
    
    while (1) {
        vga_put_pixel(x1, y1, color);
        
        if (x1 == x2 && y1 == y2) break;
        
        int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x1 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y1 += sy;
        }
    }
}

void vga_draw_char(int x, int y, char c, uint8_t fg, uint8_t bg) {
    if ((unsigned char)c > 127) c = '?';
    
    const uint8_t* glyph = font8x8[(int)c];
    
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            uint8_t pixel = (glyph[row] >> col) & 1;
            vga_put_pixel(x + col, y + row, pixel ? fg : bg);
        }
    }
}

void vga_draw_string(int x, int y, const char* str, uint8_t fg, uint8_t bg) {
    int orig_x = x;
    while (*str) {
        if (*str == '\n') {
            x = orig_x;
            y += 8;
        } else {
            vga_draw_char(x, y, *str, fg, bg);
            x += 8;
        }
        str++;
    }
}

void vga_set_palette(uint8_t index, uint8_t r, uint8_t g, uint8_t b) {
    outb(VGA_DAC_WRITE_INDEX, index);
    outb(VGA_DAC_DATA, r);
    outb(VGA_DAC_DATA, g);
    outb(VGA_DAC_DATA, b);
}

