void text_clear_screen(void) {
    for (int i = 0; i < VGA_TEXT_WIDTH * VGA_TEXT_HEIGHT; i++) {
        text_memory[i] = 0x0720;
    }
    text_cursor_x = 0;
    text_cursor_y = 0;
}

void text_print(const char* str) {
    while (*str) {
        if (*str == '\n') {
            text_cursor_x = 0;
            text_cursor_y++;
        } else {
            text_memory[text_cursor_y * VGA_TEXT_WIDTH + text_cursor_x] = 
                (uint16_t)*str | (0x07 << 8);
            text_cursor_x++;
            if (text_cursor_x >= VGA_TEXT_WIDTH) {
                text_cursor_x = 0;
                text_cursor_y++;
            }
        }
        if (text_cursor_y >= VGA_TEXT_HEIGHT) {
            text_cursor_y = VGA_TEXT_HEIGHT - 1;
        }
        str++;
    }
}

void text_print_at(const char* str, int x, int y, uint8_t color) {
    while (*str) {
        if (x < VGA_TEXT_WIDTH && y < VGA_TEXT_HEIGHT) {
            text_memory[y * VGA_TEXT_WIDTH + x] = (uint16_t)*str | ((uint16_t)color << 8);
        }
        x++;
        str++;
    }
}

void text_set_cursor(int x, int y) {
    text_cursor_x = x;
    text_cursor_y = y;
}
